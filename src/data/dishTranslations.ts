/**
 * Helper to compute display title and formatted description according to user rule:
 * - Turkish name is ALWAYS the main title on the card / modal
 * - The item in the cart is ALWAYS strictly in Turkish
 * - In non-Turkish locales, the description is formatted as:
 *   "[Localized Name]: [Localized Description]"
 */
export function getDishDisplay(
  item: {
    id: string;
    name?: any;
    description?: string;
    descriptions?: Partial<Record<Locale, string>>;
  },
  locale: string
) {
  const trans = DISH_TRANSLATIONS[item.id];
  const loc = (locale || "tr") as Locale;

  // 1. Main Title: ALWAYS Turkish
  const turkishTitle =
    (typeof item.name === "object" ? item.name?.tr : null) ||
    trans?.name?.tr ||
    (typeof item.name === "string" ? item.name : item.id);

  // 2. Name in the requested locale
  const localizedName =
    trans?.name?.[loc] ||
    (typeof item.name === "object" ? item.name?.[loc] : null) ||
    turkishTitle;

  // 3. Description in the requested locale
  const localizedDesc =
    trans?.desc?.[loc] ||
    item.descriptions?.[loc] ||
    item.description ||
    trans?.desc?.tr ||
    "";

  // 4. Formatted description according to user rule:
  // "العنوان الرئيسي بالتركي الوصف يكتب فيه الاسم باللغه المختاره وبعده الوصف باللغه المختاره"
  // If locale === "tr", just the Turkish description.
  // If locale !== "tr", "[Localized Name]: [Localized Description]"
  const formattedDesc =
    loc === "tr"
      ? localizedDesc
      : localizedDesc
      ? `${localizedName}: ${localizedDesc}`
      : localizedName;

  return {
    turkishTitle,
    localizedName,
    localizedDesc,
    formattedDesc,
  };
}
